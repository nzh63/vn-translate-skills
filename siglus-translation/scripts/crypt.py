def parse_key(s):
    """'03 5e a6 ..' / '035ea6..' → 16 字节 key（容忍空格/逗号/换行/0x 前缀）"""
    import re
    h = re.sub(r'\s|,|0x', '', s.strip(), flags=re.I)
    if len(h) != 32:
        raise SystemExit(f'key 需为 16 字节的十六进制（32 个 hex 字符），得到 {len(h)} 字符')
    try:
        return bytes.fromhex(h)
    except ValueError:
        raise SystemExit('key 含非十六进制字符')


def load_key(path):
    lines = [l for l in open(path, encoding='utf-8').read().splitlines()
             if l.strip() and not l.lstrip().startswith('#')]
    return parse_key('\n'.join(lines))


def xor_key16(buf, key):
    """decrypt1/encrypt1：16 字节密钥循环 XOR（对称）。key 为空则原样返回。"""
    if not key:
        return buf
    k = key * (len(buf) // 16 + 1)
    return bytes(a ^ b for a, b in zip(buf, k))


def xor_table(buf, tbl):
    """decrypt2/encrypt2：256 字节固定表循环 XOR（对称）。type 由选表决定。"""
    k = tbl * (len(buf) // 256 + 1)
    return bytes(a ^ b for a, b in zip(buf, k))


def xor_u16_words(words, index):
    """ss 字符串混淆/还原：每个 u16 码元 ^ (28807*index)%65536（对称）。"""
    k = (28807 * index) % 65536
    return [w ^ k for w in words]


def lzss_decompress(data, out_size):
    """解压 LZSS 裸流（不含 8 字节头）。输出不足/越界即抛 ValueError。"""
    out = bytearray()
    i = 0
    n = len(data)
    while len(out) < out_size:
        if i >= n:
            raise ValueError(f'输入耗尽 @out={len(out)}')
        flags = data[i]
        i += 1
        for bit in range(8):
            if len(out) >= out_size:
                break
            if flags >> bit & 1:
                if i >= n:
                    raise ValueError('输入耗尽（字面量）')
                out.append(data[i])
                i += 1
            else:
                if i + 2 > n:
                    raise ValueError('输入耗尽（回引）')
                tok = data[i] | data[i + 1] << 8
                i += 2
                ln = (tok & 0x0F) + 2
                off = tok >> 4
                if off == 0 or off > len(out):
                    raise ValueError(f'非法回引 off={off} @out={len(out)}（密钥错误或流损坏）')
                base = len(out) - off
                for j in range(ln):
                    out.append(out[base + j])
    if len(out) != out_size:
        raise ValueError('解压长度不符')
    return bytes(out)


def lzss_compress(raw, level=17):
    """压缩为 [u32 压缩长][u32 解压长][LZSS 流]。
    贪心最长匹配：窗口 0xFFF，匹配长上限 = level（2..17，与官方 compress 一致）。
    --store 模式可用 lzss_store()（全字面量，合法但体积大）。"""
    level = max(2, min(17, level))
    n = len(raw)
    # head[pos] -> 位置链（窗口内候选），避免 O(n·window) 全扫
    head = {}
    prev = [0] * n
    out = bytearray(struct.pack('<II', 0, n))
    pos = 0
    while pos < n:
        ctrl_at = len(out)
        out.append(0)
        ctrl = 0
        for bit in range(8):
            if pos >= n:
                break
            best_len = 0
            best_off = 0
            maxlen = min(level, n - pos)
            if maxlen >= 2 and pos > 0:
                cand = head.get(raw[pos])
                limit = pos - 0xFFF
                steps = 0
                while cand is not None and cand > limit and steps < 4096:
                    steps += 1
                    l = 0
                    while l < maxlen and raw[cand + l] == raw[pos + l]:
                        l += 1
                    if l > best_len:
                        best_len, best_off = l, pos - cand
                        if l >= maxlen:
                            break
                    cand = prev[cand]
            if best_len >= 2:
                tok = (best_off << 4) | (best_len - 2)
                out += tok.to_bytes(2, 'little')
                end = pos + best_len
                while pos < end:
                    nxt = head.get(raw[pos], 0)
                    prev[pos] = nxt
                    head[raw[pos]] = pos
                    pos += 1
            else:
                ctrl |= 1 << bit
                out.append(raw[pos])
                nxt = head.get(raw[pos], 0)
                prev[pos] = nxt
                head[raw[pos]] = pos
                pos += 1
        out[ctrl_at] = ctrl
    struct.pack_into('<I', out, 0, len(out))
    return bytes(out)


def lzss_store(raw):
    """伪压缩：全字面量 LZSS 流（每 8 字节一个 0xFF 控制位）+ 标准头。
    压缩失败时的兜底，任何解压器都接受。"""
    out = bytearray(struct.pack('<II', 0, len(raw)))
    for g in range(0, len(raw), 8):
        out.append(0xFF)
        out += raw[g:g + 8]
    struct.pack_into('<I', out, 0, len(out))
    return bytes(out)


def decompress_blob(blob, table=TBL_SCENE, key=b''):
    """场景/Gameexe 数据块 → 原文：先 decrypt2(type 表) 再 decrypt1(key)，去 8 字节头解压。"""
    dec = xor_table(blob, table)
    if key:
        dec = xor_key16(dec, key)
    comp_size, decomp_size = struct.unpack_from('<II', dec, 0)
    if comp_size != len(dec):
        raise ValueError(
            f'压缩长 {comp_size} != 数据块 {len(dec)} —— 密钥几乎肯定不对'
            f'（前 4 字节明文恰为块长的补码校验点）')
    return lzss_decompress(dec[8:], decomp_size)


def compress_blob(raw, table=TBL_SCENE, key=b'', level=17):
    """原文 → 加密压缩块：LZSS 压缩（带头）→ encrypt1(key) → encrypt2(table)。"""
    comp = lzss_compress(raw, level)
    if key:
        comp = xor_key16(comp, key)
    return xor_table(comp, table)
